use std::env;
use std::fs;
use std::path::PathBuf;

fn main() {
    println!("cargo:rerun-if-env-changed=GITHUB_ACTIONS");
    assert!(
        env::var_os("GITHUB_ACTIONS").is_none(),
        "PearlMiner builds and tests must run on the local Mac, not GitHub Actions"
    );
    let manifest_dir = PathBuf::from(env::var("CARGO_MANIFEST_DIR").unwrap());
    let metal_dir = manifest_dir.join("../csrc/metal");
    let msl_path = metal_dir.join("kernels/pearl_kernels.metal");
    let mm_path = metal_dir.join("pearl_metal.mm");
    let h_path = metal_dir.join("pearl_metal.h");

    println!("cargo:rerun-if-changed={}", msl_path.display());
    println!("cargo:rerun-if-changed={}", mm_path.display());
    println!("cargo:rerun-if-changed={}", h_path.display());

    let out_dir = PathBuf::from(env::var("OUT_DIR").unwrap());
    let embedded_h = out_dir.join("kernels_embedded.h");

    let msl_bytes = fs::read(&msl_path).expect("failed to read pearl_kernels.metal");
    let mut header = String::with_capacity(msl_bytes.len() * 4 + 256);
    header.push_str("/* Generated by core/build.rs — do not edit. */\n");
    header.push_str("static const unsigned char PEARL_KERNELS_MSL[] = {");
    for (i, b) in msl_bytes.iter().enumerate() {
        if i > 0 {
            header.push(',');
        }
        header.push_str(&b.to_string());
    }
    header.push_str("};\n");
    header.push_str(&format!(
        "static const unsigned long PEARL_KERNELS_MSL_LEN = {};\n",
        msl_bytes.len()
    ));
    fs::write(&embedded_h, header).expect("failed to write kernels_embedded.h");

    cc::Build::new()
        .cpp(true)
        .file(&mm_path)
        .include(&metal_dir)
        .include(&out_dir)
        .flag("-std=c++17")
        .flag("-O2")
        .flag("-fobjc-arc")
        .compile("pearlmetal");

    println!("cargo:rustc-link-lib=framework=Metal");
    println!("cargo:rustc-link-lib=framework=Foundation");
    println!("cargo:rustc-link-lib=framework=IOKit");
    println!("cargo:rustc-link-lib=framework=CoreFoundation");
    println!("cargo:rustc-link-lib=IOReport");
}
